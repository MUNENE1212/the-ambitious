/** Hydrate a Firestore forum post doc with backward-compat defaults */
export function hydrateForumPost(id: string, data: Record<string, unknown>): ForumPost {
  return {
    ...data,
    id,
    pinned: (data.pinned as boolean) ?? false,
    authorTitles: (data.authorTitles as MemberTitle[]) ?? [],
    replies: ((data.replies as ForumReply[]) ?? []).map(r => ({
      ...r,
      authorTitles: r.authorTitles ?? [],
    })),
  } as ForumPost;
}

