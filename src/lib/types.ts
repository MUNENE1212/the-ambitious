export interface Member {
  id: string;
  name: string;
  phone: string; // +254...
  role: Role;
  pinHash: string;
  mustChangePin: boolean;
  titles: MemberTitle[];
  secondary: boolean; // minor/secondary member per constitution Section B — higher monthly dues
  representing?: string; // adult's profile: memberId of the secondary member they represent
  representedBy?: string; // secondary member's own profile (if one exists): the adult's memberId
  failedAttempts: number;
  lockedUntil: number | null;
  isLocked: boolean; // computed at hydration: lockedUntil > Date.now()
  active: boolean;
  joinedAt: string; // YYYY-MM-DD
  createdAt: number;
  updatedAt: number;
}

/** Hydrate a Firestore member doc with computed fields */
export function hydrateMember(id: string, data: Record<string, unknown>): Member {
  const lockedUntil = (data.lockedUntil as number | null) ?? null;
  return {
    ...data,
    id,
    titles: (data.titles as MemberTitle[]) ?? [],
    secondary: (data.secondary as boolean) ?? false,
    lockedUntil,
    isLocked: lockedUntil !== null && lockedUntil > Date.now(),
  } as Member;
}

export interface Contribution {
  id: string;
  memberId: string;
  memberName: string;
  purpose: ContributionPurpose;
  month: string; // YYYY-MM — the month this charge belongs to
  amount: number;
  fineAmount: number;
  status: ContributionStatus;
  /**
   * Whether the fine on this record has actually been settled. Members often
   * pay the dues and leave the fine, so 'Paid' alone cannot mean both were
   * collected. Undefined on records written before this existed, which were
   * all-or-nothing — hydrateContribution defaults those to `status === 'Paid'`.
   */
  finePaid?: boolean;
  mpesaCode?: string;
  mpesaMessage?: string;
  treasurerMpesaCode?: string;
  verifiedBy?: string;
  verifiedAt?: number;
  paymentMethod?: PaymentMethod;
  paidDate?: string;
  recordedBy?: string;
  createdAt: number;
  updatedAt: number;
}

/** Hydrate a Firestore contribution doc with backward-compat defaults */
export function hydrateContribution(id: string, data: Record<string, unknown>): Contribution {
  return {
    ...data,
    id,
    purpose: (data.purpose as ContributionPurpose) ?? 'monthly',
    fineAmount: (data.fineAmount as number) ?? 0,
    finePaid: (data.finePaid as boolean | undefined) ?? data.status === 'Paid',
  } as Contribution;
}

